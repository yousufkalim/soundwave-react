import React, { FC, useState } from 'react';
import RightSide from '../RightSide/index';
import Header from '../../components/Header/index';
import LeftSide from '../LeftSide/index';
interface DataSetProps {
  time: number;
  levels: number[];
  songName: string;
  trackId: string;
}
interface SelectedAlbumProps {
  id: string;
  label: string;
  photo: string;
  singerName: string;
}
const index: FC = () => {
  // states for step # 2
  const [dataSets, setDataSets] = useState<DataSetProps[]>([]);
  const [selectedAlbum, setSelectedAlbum] = useState<SelectedAlbumProps>();
  // states for step # 2
  // ------> states for description
  const [autoGeneratedAlbumDescripition, setAutoGeneratedAlbumDescripition] = useState<string>('');
  const [customAlbumDescripition, setCustomAlbumDescripition] = useState<string>('');
  // ------> states for checkboxes
  const [autoGeneratedDescription, setAutoGeneratedDescription] = useState<boolean>(false);
  const [customDescription, setCustomDescription] = useState<boolean>(false);

  const handleDataSets = (val: DataSetProps[]) => {
    setDataSets(val);
  };
  const posterDescription = autoGeneratedDescription
    ? autoGeneratedAlbumDescripition
    : customAlbumDescripition;
  return (
    <>
      <Header />
      <div className="flex h-[80vh]">
        <LeftSide
          dataSets={dataSets}
          albumDescripition={posterDescription}
          selectedAlbum={selectedAlbum}
        />
        <RightSide
          handleDataSets={handleDataSets}
          selectedAlbum={selectedAlbum}
          setSelectedAlbum={setSelectedAlbum}
          // props for step # 2
          autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
          setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
          customAlbumDescripition={customAlbumDescripition}
          setCustomAlbumDescripition={setCustomAlbumDescripition}
          autoGeneratedDescription={autoGeneratedDescription}
          setAutoGeneratedDescription={setAutoGeneratedDescription}
          customDescription={customDescription}
          setCustomDescription={setCustomDescription}
        />
      </div>
    </>
  );
};

export default index;
