import html2canvas from 'html2canvas';
import Step1 from '../PosterSteps/step1';
import Step2 from '../PosterSteps/step2';
import Step3 from '../PosterSteps/step3';
import Step4 from '../PosterSteps/step4';
import Step5 from '../PosterSteps/step5';
import { ReactComponent as TitleIcon } from '../../assets/titleIcon.svg';
import { ReactComponent as Cart } from '../../assets/cart.svg';
import request from '../../api/request';
import { toast } from 'react-toastify';
interface DataSetProps {
  songName: string;
  trackId: string;
  time: number;
  levels: number[];
}
interface SelectedAlbumProps {
  id: string;
  label: string;
  photo: string;
  singerName: string;
}
interface IPosterSize {
  value: string;
  unit: string;
}
interface RightSideProps {
  selected: string;
  setSelected: (value: string) => void;
  handleDataSets: (val: DataSetProps[]) => void;
  selectedAlbum?: SelectedAlbumProps;
  setSelectedAlbum: (value: SelectedAlbumProps) => void;
  setAutoGeneratedAlbumDescripition: (value: string) => void;
  autoGeneratedAlbumDescripition: string;
  autoGeneratedDescription: boolean;
  setAutoGeneratedDescription: (value: boolean) => void;
  customDescription: boolean;
  setCustomDescription: (value: boolean) => void;
  customAlbumDescripition: string;
  setCustomAlbumDescripition: (value: string) => void;
  boxColor: string;
  descriptionColor: string;
  posterColor: string;
  soundWaveColor: string;
  songTitleColor: string;
  posterSize: IPosterSize;
  setPosterSize: ({ value, unit }: IPosterSize) => void;
  addToCart: boolean;
  setAddToCart: (value: boolean) => void;
  primaryColor: string;
  selectedTemplate: string;
  setSelectedTemplate: (value: string) => void;
  getSetColor: (currentColor: string, fieldName: string) => void;
  frame: IFrameProps;
  setFrame: ({ frameType, selectedFrame }: IFrameProps) => void;
  handleResetData: () => void;
  setLoading: (loading: boolean) => void;
  getCartData: (value: string) => void;
  openDescripition: boolean;
  setOpenDescripition: (value: boolean) => void;
  openTheme: boolean;
  setOpenTheme: (value: boolean) => void;
  openStyles: boolean;
  setOpenStyles: (value: boolean) => void;
  openSize: boolean;
  setOpenSize: (value: boolean) => void;
  activeStep: number;
  setActiveStep: (value: number) => void;
}

interface IFrameProps {
  frameType: string;
  selectedFrame: string;
}

interface IResponsePoster {
  frame: IFrameProps;
  size: IPosterSize;
  albumName: string;
  singerName: string;
  price: number;
  posterImage: string;
  posterQuantity: number;
  _id: string;
}
interface IResponseCart {
  _id: string;
  totalPoster: IResponsePoster[];
  totalPrice: number;
  shippingCost: number;
  createdAt?: string;
  updatedAt?: string;
  __v?: number;
}

interface IResponseSuccess {
  success: boolean;
  cart: IResponseCart;
}

interface IBodyTotalPoster {
  posterImage?: string;
  posterQuantity: number;
  unitPrice: number;
  totalPrice: number;
  size: IPosterSize;
  frame: IFrameProps;
  albumName?: string;
  singerName?: string;
}
interface IBody {
  totalPoster: IBodyTotalPoster[];
  cartId?: string;
}

const RightSide: FC<RightSideProps> = ({
  selected,
  setSelected,
  handleDataSets,
  selectedAlbum,
  setSelectedAlbum,
  autoGeneratedAlbumDescripition,
  setAutoGeneratedAlbumDescripition,
  autoGeneratedDescription,
  setAutoGeneratedDescription,
  customDescription,
  setCustomDescription,
  customAlbumDescripition,
  setCustomAlbumDescripition,
  posterColor,
  boxColor,
  soundWaveColor,
  songTitleColor,
  descriptionColor,
  getSetColor,
  posterSize,
  setPosterSize,
  addToCart,
  setAddToCart,
  primaryColor,
  selectedTemplate,
  setSelectedTemplate,
  frame,
  setFrame,
  handleResetData,
  setLoading,
  getCartData,
  openDescripition,
  setOpenDescripition,
  openTheme,
  setOpenTheme,
  openStyles,
  setOpenStyles,
  openSize,
  setOpenSize,
  activeStep,
  setActiveStep,
}) => {
  const handleAddToCart = async () => {
    // const element = document.getElementById('custom-poster-template-1') as HTMLElement;
    // const canvas = await html2canvas(element, { allowTaint: true });
    // const imgData = canvas.toDataURL('image/png');
    const cartId = localStorage.getItem('cartId');
    setLoading(true);
    const posterData: IBody = {
      totalPoster: [
        {
          posterImage: selectedAlbum?.photo,
          posterQuantity: 1,
          unitPrice: 120,
          totalPrice: 120,
          size: posterSize,
          frame,
          albumName: selectedAlbum?.label,
          singerName: selectedAlbum?.singerName,
        },
      ],
    };

    if (cartId) {
      posterData.cartId = cartId;
    }
    setAddToCart(!addToCart);
    try {
      const data = await request<IResponseSuccess, IBody>('post', '/cart/add-poster', posterData);
      const cart = data.data.cart;
      localStorage.setItem('cartId', cart._id);
      handleResetData();
      getCartData(cart._id);
      setLoading(false);
      toast.success('Poster Added To Cart');
    } catch (err) {
      setLoading(false);
      console.log('Add cart Error ');
    }
  };
  return (
    <div className="bg-white w-[44%] flex items-start justify-start mt-11 pl-20">
      <div className="w-[60%]">
        <div className="w-full flex items-center justify-start">
          <TitleIcon className="mx-2" />
          <span className="text-lg font-semibold tracking-tight text-black">Soundwave Poster</span>
        </div>
        <div className="w-full flex items-center justify-start mb-7">
          <i className="text-[#454238] text-3xl tracking-tight font-semibold">
            Let’s Start with your Content
          </i>
        </div>
        <div className="mb-2">
          <span className="text-[#454238] text-sm font-semibold ">Search an Album or Artist</span>
        </div>
        <div className="flex flex-col gap-3">
          <Step1
            handleDataSets={handleDataSets}
            selectedAlbum={selectedAlbum}
            setSelectedAlbum={setSelectedAlbum}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            selected={selected}
            setSelected={setSelected}
          />
          <Step2
            openDescripition={openDescripition}
            setOpenDescripition={setOpenDescripition}
            setOpenTheme={setOpenTheme}
            setOpenStyles={setOpenStyles}
            selectedAlbum={selectedAlbum}
            autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
            setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
            customAlbumDescripition={customAlbumDescripition}
            setCustomAlbumDescripition={setCustomAlbumDescripition}
            autoGeneratedDescription={autoGeneratedDescription}
            setAutoGeneratedDescription={setAutoGeneratedDescription}
            customDescription={customDescription}
            setCustomDescription={setCustomDescription}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
          <Step3
            primaryColor={primaryColor}
            openTheme={openTheme}
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            setOpenStyles={setOpenStyles}
            boxColor={boxColor}
            posterColor={posterColor}
            soundWaveColor={soundWaveColor}
            songTitleColor={songTitleColor}
            descriptionColor={descriptionColor}
            getSetColor={getSetColor}
            selectedTemplate={selectedTemplate}
            setSelectedTemplate={setSelectedTemplate}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
          <Step4
            openStyles={openStyles}
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            setOpenStyles={setOpenStyles}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            frame={frame}
            setFrame={setFrame}
          />
          <Step5
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            posterSize={posterSize}
            setPosterSize={setPosterSize}
            openSize={openSize}
            setOpenStyles={setOpenStyles}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
          <button
            className={
              activeStep === 6
                ? 'bg-black flex items-center justify-center h-14 rounded-xl cursor-pointer'
                : 'bg-[#919B9B] flex items-center justify-center h-14 rounded-xl'
            }
            onClick={handleAddToCart}
            // disabled={activeStep < 6}
          >
            <span className="text-white flex">
              <Cart />
              &nbsp;&nbsp;&nbsp;&nbsp;Add To Cart&nbsp;<b>$10.00</b>
            </span>
          </button>
        </div>
      </div>
    </div>
  );
};

export default RightSide;
