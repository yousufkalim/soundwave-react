import React, { FC, useState, useEffect } from 'react';
import html2canvas from 'html2canvas';
import Step1 from '../PosterSteps/step1';
import Step2 from '../PosterSteps/step2';
import Step3 from '../PosterSteps/step3';
import Step4 from '../PosterSteps/step4';
import Step5 from '../PosterSteps/step5';
import { ReactComponent as TitleIcon } from '../../assets/titleIcon.svg';
import { ReactComponent as Cart } from '../../assets/cart.svg';
import request from '../../api/request';
import { toast } from 'react-toastify';
import {
  IPosterSize,
  SelectedAlbumProps,
  DataSetProps,
  // IResponsePoster,
  IResponseCart,
} from '../../types/index';
import { PricingArray } from '../../utils/data';
import Tab from '../Tab/index';
import { Collapse, StepLabel } from '@mui/material';
import Fade from 'react-reveal/Fade';
import Box from '@mui/material/Box';
import Stepper from '@mui/material/Stepper';
import Step from '@mui/material/Step';
import StepButton from '@mui/material/StepButton';
import { styled } from '@mui/material/styles';
import StepConnector, { stepConnectorClasses } from '@mui/material/StepConnector';
import { ReactComponent as NextArrowBtn } from '../../assets/nextArrowBtn.svg';
const QontoConnector = styled(StepConnector)(({ theme }) => ({
  [`&.${stepConnectorClasses.alternativeLabel}`]: {
    top: 10,
    left: 'calc(-50% + 16px)',
    right: 'calc(50% + 16px)',
  },
  [`&.${stepConnectorClasses.active}`]: {
    [`& .${stepConnectorClasses.line}`]: {
      borderColor: 'black',
    },
  },
  [`&.${stepConnectorClasses.completed}`]: {
    [`& .${stepConnectorClasses.line}`]: {
      borderColor: 'black',
    },
  },
  [`& .${stepConnectorClasses.line}`]: {
    borderColor: theme.palette.mode === 'dark' ? theme.palette.grey[800] : '#919B9B',
    borderTopWidth: 3,
    borderRadius: 1,
  },
}));
interface RightSideProps {
  selected: string;
  setSelected: (value: string) => void;
  handleDataSets: (val: DataSetProps[]) => void;
  selectedAlbum?: SelectedAlbumProps;
  setSelectedAlbum: (value: SelectedAlbumProps) => void;
  setAutoGeneratedAlbumDescripition: (value: string) => void;
  autoGeneratedAlbumDescripition: string;
  autoGeneratedDescription: boolean;
  setAutoGeneratedDescription: (value: boolean) => void;
  customDescription: boolean;
  setCustomDescription: (value: boolean) => void;
  customAlbumDescripition: string;
  setCustomAlbumDescripition: (value: string) => void;
  boxColor: string;
  descriptionColor: string;
  posterColor: string;
  soundWaveColor: string;
  songTitleColor: string;
  soundWaveNameColor: string;
  posterSize: IPosterSize;
  setPosterSize: ({ value, unit }: IPosterSize) => void;
  addToCart: boolean;
  setAddToCart: (value: boolean) => void;
  selectedTemplate: string;
  setSelectedTemplate: (value: string) => void;
  getSetColor: (currentColor: string, fieldName: string) => void;
  posterType: string;
  setPosterType: (value: string) => void;
  handleResetData: () => void;
  setLoading: (loading: boolean) => void;
  getCartData: (value: string) => void;
  openDescripition: boolean;
  setOpenDescripition: (value: boolean) => void;
  openTheme: boolean;
  setOpenTheme: (value: boolean) => void;
  openStyles: boolean;
  setOpenStyles: (value: boolean) => void;
  openSize: boolean;
  setOpenSize: (value: boolean) => void;
  activeStep: number;
  setActiveStep: (value: number) => void;
  setOpen: (value: boolean) => void;
  selectedFont: string;
  setSelectedFont: (value: string) => void;
  setFlag: (value: boolean) => void;
}

interface IResponseSuccess {
  success: boolean;
  cart: IResponseCart;
}

interface IBodyTotalPoster {
  posterImage?: string;
  posterQuantity: number;
  unitPrice: number;
  totalPrice: number;
  size: IPosterSize;
  posterType: string;
  albumName?: string;
  singerName?: string;
}
interface IBody {
  totalPoster: IBodyTotalPoster[];
  cartId?: string;
}
const steps = ['Album', 'Description', 'Theme', 'Print', 'Size'];

const RightSide: FC<RightSideProps> = ({
  selected,
  setSelected,
  handleDataSets,
  selectedAlbum,
  setSelectedAlbum,
  autoGeneratedAlbumDescripition,
  setAutoGeneratedAlbumDescripition,
  autoGeneratedDescription,
  setAutoGeneratedDescription,
  customDescription,
  setCustomDescription,
  customAlbumDescripition,
  setCustomAlbumDescripition,
  posterColor,
  boxColor,
  soundWaveColor,
  songTitleColor,
  soundWaveNameColor,
  descriptionColor,
  getSetColor,
  posterSize,
  setPosterSize,
  addToCart,
  setAddToCart,
  selectedTemplate,
  setSelectedTemplate,
  posterType,
  setPosterType,
  handleResetData,
  setLoading,
  getCartData,
  openDescripition,
  setOpenDescripition,
  openTheme,
  setOpenTheme,
  openStyles,
  setOpenStyles,
  openSize,
  setOpenSize,
  activeStep,
  setActiveStep,
  setOpen,
  selectedFont,
  setSelectedFont,
  setFlag,
}) => {
  const [posterPrice, setPosterPrice] = useState<number>(0);
  const [activeStepperStep, setActiveStepperStep] = useState<number>(0);

  const handleCalulatePosterPrice = (): void => {
    const posterSizePriceResult = PricingArray.posterSizePricing.find((item) => {
      const currentUnit = posterSize.unit === 'inch' ? item.inch : item.centimeter;
      if (posterSize.value === currentUnit) {
        return item;
      }
      return undefined;
    });

    const posterFramePriceResult = PricingArray.posterTypePricing.find((item) => {
      const currentUnit = posterSize.unit === 'inch' ? item.inch : item.centimeter;
      if (posterSize.value === currentUnit) {
        return item;
      }
      return undefined;
    });

    const totalPrice =
      (posterSizePriceResult?.price ?? 0) +
      (posterType === 'Black Wooden Frame' ||
      posterType === 'Nuteral Wooden Frame' ||
      posterType === 'White Wooden Frame' ||
      posterType === 'Black Metal Frame'
        ? posterFramePriceResult?.withFramePrice ?? 0
        : posterType === 'No Frame'
        ? 0
        : posterType === 'Thin Canvas'
        ? posterFramePriceResult?.slimCanvasPrice ?? 0
        : posterType === 'Thick Canvas'
        ? posterFramePriceResult?.thickCanvasPrice ?? 0
        : 0);

    setPosterPrice(+totalPrice.toFixed(2));
  };

  useEffect(() => {
    handleCalulatePosterPrice();
  }, [posterSize, posterType]);

  const handleAddToCart = () => {
    setLoading(true);
    setFlag(true);
    setTimeout(async () => {
      const element = document.getElementById('custom-poster-template') as HTMLElement;
      const canvas = await html2canvas(element, {
        logging: false,
        allowTaint: true,
        scale: 3,
        useCORS: true,
      });
      const img = canvas.toDataURL();
      const cartId = localStorage.getItem('cartId');

      const posterData: IBody = {
        totalPoster: [
          {
            posterImage: img,
            posterQuantity: 1,
            unitPrice: posterPrice,
            totalPrice: posterPrice,
            size: posterSize,
            posterType,
            albumName: selectedAlbum?.label,
            singerName: selectedAlbum?.singerName,
          },
        ],
      };

      if (cartId) {
        posterData.cartId = cartId;
      }
      setAddToCart(!addToCart);

      await request<IResponseSuccess, IBody>('post', '/cart/add-poster', posterData)
        .then((res) => {
          localStorage.setItem('cartId', res?.data?.cart?._id);
          handleResetData();
          getCartData(res?.data?.cart?._id);
          setLoading(false);
          setOpen(true);
          toast.success('Poster Added To Cart');
        })
        .catch((err) => {
          setLoading(false);
          console.log('Add cart Error ', err);
        });
    }, 100);
  };

  const handleDescripitionTabClick = (): void => {
    if (activeStep >= 2) {
      setOpenDescripition(!openDescripition);
      setOpenTheme(false);
      setOpenStyles(false);
      setOpenSize(false);
      setActiveStep(3);
    } else {
      setOpenDescripition(false);
      setOpenTheme(false);
      setOpenStyles(false);
      setOpenSize(false);
    }
  };
  const handleThemeTabClick = (): void => {
    if (activeStep >= 3) {
      setOpenTheme(!openTheme);
      setOpenDescripition(false);
      setOpenStyles(false);
      setOpenSize(false);
      setActiveStep(4);
    } else {
      setOpenTheme(false);
      setOpenDescripition(false);
      setOpenStyles(false);
      setOpenSize(false);
    }
  };
  const handlePrintFormatTabClick = (): void => {
    if (activeStep >= 4) {
      setOpenStyles(!openStyles);
      setOpenDescripition(false);
      setOpenTheme(false);
      setOpenSize(false);
      setActiveStep(5);
    } else {
      setOpenStyles(false);
      setOpenDescripition(false);
      setOpenTheme(false);
      setOpenSize(false);
    }
  };

  const handleSizeTabClick = (): void => {
    if (activeStep >= 5) {
      setOpenSize(!openSize);
      setOpenStyles(false);
      setOpenDescripition(false);
      setOpenTheme(false);
      setActiveStep(6);
    } else {
      setOpenSize(false);
      setOpenStyles(false);
      setOpenDescripition(false);
      setOpenTheme(false);
    }
  };

  // stepper functions
  const handleNext = (): void => {
    setActiveStepperStep(activeStepperStep + 1);
  };

  const handleBack = (): void => {
    setActiveStepperStep((prevActiveStep) => prevActiveStep - 1);
  };
  return (
    <div className="bg-white w-full md:w-[40%] 2xl:w-[42%] flex items-start justify-center md:justify-start sm:mt-11 md:pl-5 lg:pl-10 sxl:pl-20">
      <div className=" w-full sm:w-[78%] md:w-[95%] lg:w-[88%] 2xl:w-[65%] sxl:w-[75%]">
        <div className="w-full hidden md:flex items-center justify-start">
          <TitleIcon className="mx-2" />
          <span className="text-sm font-semibold tracking-tight text-black">Soundwave Poster</span>
        </div>
        <div className="w-full hidden md:flex md:items-center md:justify-start md:mb-5">
          <i className="text-black text-2xl tracking-tight font-semibold">
            Let’s Start With Your Content
          </i>
        </div>
        <div className="mb-2 hidden md:block">
          <span className="text-black text-[13px] 2xl:text-[14px] font-semibold ">
            Search an Album or Artist
          </span>
        </div>
        <div className="md:flex flex-col gap-[.3rem] hidden">
          <Step1
            handleDataSets={handleDataSets}
            selectedAlbum={selectedAlbum}
            setSelectedAlbum={setSelectedAlbum}
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            selected={selected}
            setSelected={setSelected}
          />

          <Tab
            onClick={handleDescripitionTabClick}
            heading={'Description'}
            open={openDescripition}
            active={activeStep >= 2}
          />
          <Collapse in={openDescripition} timeout={600}>
            <Fade when={openDescripition} duration={500}>
              <Step2
                selectedAlbum={selectedAlbum}
                autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
                setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
                customAlbumDescripition={customAlbumDescripition}
                setCustomAlbumDescripition={setCustomAlbumDescripition}
                autoGeneratedDescription={autoGeneratedDescription}
                setAutoGeneratedDescription={setAutoGeneratedDescription}
                customDescription={customDescription}
                setCustomDescription={setCustomDescription}
              />
            </Fade>
          </Collapse>
          <Tab
            onClick={handleThemeTabClick}
            heading={'Theme'}
            open={openTheme}
            active={activeStep >= 3}
          />
          <Collapse in={openTheme} timeout={600}>
            <Fade when={openTheme} duration={500}>
              <Step3
                boxColor={boxColor}
                posterColor={posterColor}
                soundWaveColor={soundWaveColor}
                songTitleColor={songTitleColor}
                descriptionColor={descriptionColor}
                getSetColor={getSetColor}
                selectedTemplate={selectedTemplate}
                soundWaveNameColor={soundWaveNameColor}
                setSelectedTemplate={setSelectedTemplate}
                selectedFont={selectedFont}
                setSelectedFont={setSelectedFont}
                setLoading={setLoading}
              />
            </Fade>
          </Collapse>
          <Tab
            open={openStyles}
            onClick={handlePrintFormatTabClick}
            heading={'Print Format'}
            active={activeStep >= 4}
          />
          <Collapse in={openStyles} timeout={600}>
            <Fade when={openStyles} duration={500}>
              <Step4 posterType={posterType} setPosterType={setPosterType} />
            </Fade>
          </Collapse>
          <Tab
            open={openSize}
            onClick={handleSizeTabClick}
            heading={'Size'}
            active={activeStep >= 5}
          />
          <Collapse in={openSize} timeout={600}>
            <Fade when={openSize} duration={500}>
              <Step5 posterSize={posterSize} setPosterSize={setPosterSize} />
            </Fade>
          </Collapse>

          <button
            style={{
              display: selected === '' ? 'none' : '',
            }}
            className={
              activeStep === 6
                ? 'bg-black flex items-center justify-center py-3 2xl:py-4 rounded-xl cursor-pointer mt-1'
                : 'bg-[#919B9B] flex items-center justify-center py-3 2xl:py-4 rounded-xl mt-1'
            }
            onClick={handleAddToCart}
          >
            <span className="text-white flex text-[.9rem] 2xl:text-[1rem]">
              <Cart />
              &nbsp;&nbsp;&nbsp;&nbsp;Add To Cart&nbsp;<b>${posterPrice}</b>
            </span>
          </button>
        </div>
        <Box className="md:hidden px-3">
          <Stepper activeStep={activeStepperStep} alternativeLabel connector={<QontoConnector />}>
            {steps.map((label, index) => (
              <Step key={label}>
                <StepButton color="inherit">
                  <p
                    className="text-[10px]"
                    style={{ color: activeStepperStep === index ? 'black' : '#919B9B' }}
                  >
                    {label}
                  </p>
                </StepButton>
              </Step>
            ))}
          </Stepper>
          <div>
            <React.Fragment>
              <div className="my-3 mb-20">
                {activeStepperStep === 0 ? (
                  <>
                    <Step1
                      handleDataSets={handleDataSets}
                      selectedAlbum={selectedAlbum}
                      setSelectedAlbum={setSelectedAlbum}
                      // steps active states
                      activeStep={activeStep}
                      setActiveStep={setActiveStep}
                      selected={selected}
                      setSelected={setSelected}
                    />
                  </>
                ) : activeStepperStep === 1 ? (
                  <>
                    <Step2
                      selectedAlbum={selectedAlbum}
                      autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
                      setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
                      customAlbumDescripition={customAlbumDescripition}
                      setCustomAlbumDescripition={setCustomAlbumDescripition}
                      autoGeneratedDescription={autoGeneratedDescription}
                      setAutoGeneratedDescription={setAutoGeneratedDescription}
                      customDescription={customDescription}
                      setCustomDescription={setCustomDescription}
                    />
                  </>
                ) : activeStepperStep === 2 ? (
                  <>
                    <Step3
                      boxColor={boxColor}
                      posterColor={posterColor}
                      soundWaveColor={soundWaveColor}
                      songTitleColor={songTitleColor}
                      descriptionColor={descriptionColor}
                      getSetColor={getSetColor}
                      selectedTemplate={selectedTemplate}
                      soundWaveNameColor={soundWaveNameColor}
                      setSelectedTemplate={setSelectedTemplate}
                      selectedFont={selectedFont}
                      setSelectedFont={setSelectedFont}
                      setLoading={setLoading}
                    />
                  </>
                ) : activeStepperStep === 3 ? (
                  <>
                    <Step4 posterType={posterType} setPosterType={setPosterType} />
                  </>
                ) : (
                  activeStepperStep === 4 && (
                    <>
                      <Step5 posterSize={posterSize} setPosterSize={setPosterSize} />
                    </>
                  )
                )}
              </div>

              <Box className="flex items-end justify-center pt-2 fixed bottom-0 left-0 z-50 w-full">
                <button
                  className={
                    activeStepperStep === 0
                      ? 'text-white bg-[#3E3E3E] px-6 py-4 font-semibold w-[50%]'
                      : 'text-white bg-black px-6 py-4 font-semibold w-[50%]'
                  }
                  disabled={activeStepperStep === 0}
                  onClick={handleBack}
                >
                  Back
                </button>
                <button
                  onClick={activeStepperStep === 4 ? handleAddToCart : handleNext}
                  // disabled={activeStepperStep === 4}
                  className={'text-white bg-black  font-semibold w-[50%]'}
                >
                  {activeStepperStep === 4 ? (
                    <span className="flex items-center justify-center text-[.9rem] px-6 py-[17px]">
                      Add To Cart ${posterPrice}
                    </span>
                  ) : (
                    <span className="flex items-center justify-center gap-2 px-6 py-4">
                      Next <NextArrowBtn />
                    </span>
                  )}
                </button>
              </Box>
            </React.Fragment>
          </div>
          {/* <div
            className="w-full flex items-center justify-center my-5"
            style={{ display: activeStepperStep !== 4 ? 'none' : '' }}
          >
            <button
              className={
                'bg-black flex items-center justify-center py-3 2xl:py-4 rounded-xl cursor-pointer w-full'
              }
              onClick={handleAddToCart}
            >
              <span className="text-white flex text-[.9rem] 2xl:text-[1rem]">
                <Cart />
                &nbsp;&nbsp;&nbsp;&nbsp;Add To Cart&nbsp;<b>${posterPrice}</b>
              </span>
            </button>
          </div> */}
        </Box>
      </div>
    </div>
  );
};

export default RightSide;
