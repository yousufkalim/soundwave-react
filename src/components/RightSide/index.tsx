const RightSide: FC<RightSideProps> = ({
  selected,
  setSelected,
  handleDataSets,
  selectedAlbum,
  setSelectedAlbum,
  autoGeneratedAlbumDescripition,
  setAutoGeneratedAlbumDescripition,
  autoGeneratedDescription,
  setAutoGeneratedDescription,
  customDescription,
  setCustomDescription,
  customAlbumDescripition,
  setCustomAlbumDescripition,
  posterColor,
  boxColor,
  soundWaveColor,
  songTitleColor,
  soundWaveNameColor,
  descriptionColor,
  getSetColor,
  posterSize,
  setPosterSize,
  addToCart,
  setAddToCart,
  selectedTemplate,
  setSelectedTemplate,
  frame,
  setFrame,
  handleResetData,
  setLoading,
  getCartData,
  openDescripition,
  setOpenDescripition,
  openTheme,
  setOpenTheme,
  openStyles,
  setOpenStyles,
  openSize,
  setOpenSize,
  activeStep,
  setActiveStep,
  selectedCanvas,
  setSelectedCanvas,
  setOpen,
  selectedFont,
  setSelectedFont,
}) => {
  const [posterPrice, setPosterPrice] = useState<number>(0);

  const handleCalulatePosterPrice = (): void => {
    const posterSizePriceResult = pricingArray.posterSizePricing.find((item) => {
      const currentUnit = posterSize.unit === 'inch' ? item.inch : item.centimeter;
      if (posterSize.value === currentUnit) {
        return item;
      }
      return undefined;
    });

    const posterFramePriceResult = pricingArray.posterFramePricing.find((item) => {
      const currentUnit = posterSize.unit === 'inch' ? item.inch : item.centimeter;
      const cal =
        posterSize.value === currentUnit &&
        (frame.frameType === 'Wooden' || frame.frameType === 'Metal');
      if (cal) {
        return item;
      }
      return undefined;
    });

    const posterCanvasPriceResult = pricingArray.posterCanvasPricing.find((item) => {
      const currentUnit = posterSize.unit === 'inch' ? item.inch : item.centimeter;
      const cal =
        posterSize.value === currentUnit &&
        (selectedCanvas === '2-3 cm' || selectedCanvas === '4 cm');
      if (cal) {
        return item;
      }
      return undefined;
    });

    const totalPrice =
      (posterSizePriceResult?.price ?? 0) +
      (posterFramePriceResult?.price ?? 0) +
      (selectedCanvas === '2-3 cm'
        ? posterCanvasPriceResult?.slimCanvasPrice ?? 0
        : posterCanvasPriceResult?.thickCanvasPrice ?? 0);

    setPosterPrice(+totalPrice.toFixed(2));
  };

  useEffect(() => {
    handleCalulatePosterPrice();
  }, [posterSize, frame, selectedCanvas]);

  const handleAddToCart = async () => {
    const element = document.getElementById('custom-poster-template') as HTMLElement;
    const canvas = await html2canvas(element, {
      logging: false,
      allowTaint: true,
      scale: 3,
    });
    const img = canvas.toDataURL();
    // setSvgImage(img);
    const cartId = localStorage.getItem('cartId');
    setLoading(true);

    const posterData: IBody = {
      totalPoster: [
        {
          posterImage: img,
          posterQuantity: 1,
          unitPrice: posterPrice,
          totalPrice: posterPrice,
          size: posterSize,
          canvasSize: selectedCanvas,
          frame,
          albumName: selectedAlbum?.label,
          singerName: selectedAlbum?.singerName,
        },
      ],
    };

    if (cartId) {
      posterData.cartId = cartId;
    }
    setAddToCart(!addToCart);
    try {
      const data = await request<IResponseSuccess, IBody>('post', '/cart/add-poster', posterData);
      const cart = data.data.cart;
      localStorage.setItem('cartId', cart._id);
      handleResetData();
      getCartData(cart._id);
      setLoading(false);
      setOpen(true);
      toast.success('Poster Added To Cart');
    } catch (err) {
      setLoading(false);
      console.log('Add cart Error ');
    }
  };
  return (
    <div className="bg-white w-[40%] flex items-start justify-start mt-11 pl-20 2xl:w-[42%]">
      <div className="w-[78%] 2xl:w-[65%]">
        <div className="w-full flex items-center justify-start">
          <TitleIcon className="mx-2" />
          <span className="text-sm font-semibold tracking-tight text-black">Soundwave Poster</span>
        </div>
        <div className="w-full flex items-center justify-start mb-5">
          <i className="text-black text-2xl tracking-tight font-semibold">
            Let’s Start With Your Content
          </i>
        </div>
        <div className="mb-2">
          <span className="text-black text-sm font-semibold ">Search an Album or Artist</span>
        </div>
        <div className="flex flex-col gap-3">
          <Step1
            handleDataSets={handleDataSets}
            selectedAlbum={selectedAlbum}
            setSelectedAlbum={setSelectedAlbum}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            selected={selected}
            setSelected={setSelected}
          />
          <Step2
            openDescripition={openDescripition}
            setOpenDescripition={setOpenDescripition}
            setOpenTheme={setOpenTheme}
            setOpenStyles={setOpenStyles}
            selectedAlbum={selectedAlbum}
            autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
            setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
            customAlbumDescripition={customAlbumDescripition}
            setCustomAlbumDescripition={setCustomAlbumDescripition}
            autoGeneratedDescription={autoGeneratedDescription}
            setAutoGeneratedDescription={setAutoGeneratedDescription}
            customDescription={customDescription}
            setCustomDescription={setCustomDescription}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
          <Step3
            openTheme={openTheme}
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            setOpenStyles={setOpenStyles}
            boxColor={boxColor}
            posterColor={posterColor}
            soundWaveColor={soundWaveColor}
            songTitleColor={songTitleColor}
            descriptionColor={descriptionColor}
            getSetColor={getSetColor}
            selectedTemplate={selectedTemplate}
            soundWaveNameColor={soundWaveNameColor}
            setSelectedTemplate={setSelectedTemplate}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            // change font state
            selectedFont={selectedFont}
            setSelectedFont={setSelectedFont}
            setLoading={setLoading}
          />
          <Step4
            openStyles={openStyles}
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            setOpenStyles={setOpenStyles}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
            frame={frame}
            setFrame={setFrame}
            selectedCanvas={selectedCanvas}
            setSelectedCanvas={setSelectedCanvas}
          />
          <Step5
            setOpenTheme={setOpenTheme}
            setOpenDescripition={setOpenDescripition}
            posterSize={posterSize}
            setPosterSize={setPosterSize}
            openSize={openSize}
            setOpenStyles={setOpenStyles}
            setOpenSize={setOpenSize}
            // steps active states
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
          <button
            className={
              activeStep === 6
                ? 'bg-black flex items-center justify-center h-14 rounded-xl cursor-pointer'
                : 'bg-[#919B9B] flex items-center justify-center h-14 rounded-xl'
            }
            onClick={handleAddToCart}
            // disabled={activeStep < 6}
          >
            <span className="text-white flex">
              <Cart />
              &nbsp;&nbsp;&nbsp;&nbsp;Add To Cart&nbsp;<b>${posterPrice}</b>
            </span>
          </button>
        </div>
      </div>
      {/* <img src={svgImage} /> */}
    </div>
  );
};

export default RightSide;
