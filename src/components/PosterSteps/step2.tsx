import React, { FC, useEffect } from 'react';
import { Checkbox, Collapse } from '@mui/material';
import Tab from '../Tab/index';
import { SelectedAlbumProps } from '../../types/index';
import Fade from 'react-reveal/Fade';
interface Step2Props {
  openDescripition: boolean;
  setOpenDescripition: (value: boolean) => void;
  setOpenTheme: (value: boolean) => void;
  setOpenStyles: (value: boolean) => void;
  selectedAlbum?: SelectedAlbumProps;
  autoGeneratedAlbumDescripition?: string;
  setAutoGeneratedAlbumDescripition: (value: string) => void;
  customAlbumDescripition?: string;
  setCustomAlbumDescripition: (value: string) => void;
  autoGeneratedDescription: boolean;
  setAutoGeneratedDescription: (value: boolean) => void;
  customDescription: boolean;
  setCustomDescription: (value: boolean) => void;
  setOpenSize: (value: boolean) => void;
  activeStep: number;
  setActiveStep: (value: number) => void;
}

const step2: FC<Step2Props> = ({
  openDescripition,
  setOpenDescripition,
  setOpenTheme,
  setOpenStyles,
  selectedAlbum,
  autoGeneratedAlbumDescripition,
  setAutoGeneratedAlbumDescripition,
  customAlbumDescripition,
  setCustomAlbumDescripition,
  autoGeneratedDescription,
  setAutoGeneratedDescription,
  customDescription,
  setCustomDescription,
  setOpenSize,
  activeStep,
  setActiveStep,
}) => {
  const handleIconClick = (): void => {
    if (activeStep >= 2) {
      setOpenDescripition(!openDescripition);
      setOpenTheme(false);
      setOpenStyles(false);
      setOpenSize(false);
      setActiveStep(3);
    } else {
      setOpenDescripition(false);
      setOpenTheme(false);
      setOpenStyles(false);
      setOpenSize(false);
    }
  };
  const handleAutoGeneratedDescription = (): void => {
    setAutoGeneratedDescription(!autoGeneratedDescription);
    setCustomDescription(false);
  };

  const handleCustomDescription = (): void => {
    setCustomDescription(!customDescription);
    setAutoGeneratedDescription(false);
  };

  const handleGetAlbumInfo = (): void => {
    if (selectedAlbum) {
      const albumName = selectedAlbum.label;
      const singerName = selectedAlbum.singerName.replace(/ /g, '%20');
      fetch(
        `https://en.wikipedia.org/w/api.php?action=query&format=json&list=search&utf8=1&srsearch=${albumName}%20album%20${singerName}&format=json&origin=*`,
        {
          method: 'GET',
          credentials: 'omit',
        },
      )
        .then(async (res) => await res.json())
        .then((data) => {
          const pageId = data.query.search[0].pageid;
          fetch(
            `https://en.wikipedia.org/w/api.php?format=json&action=query&prop=extracts&exintro&explaintext&redirects=1&pageids=${pageId}&format=json&origin=*`,
            {
              method: 'GET',
              credentials: 'omit',
            },
          )
            .then(async (res1) => await res1.json())
            .then((data1) => {
              const albumDescription = data1.query.pages[Object.keys(data1.query.pages)[0]].extract;
              const lastDotIndex = albumDescription.lastIndexOf('.');
              const secondLastDotIndex = albumDescription.lastIndexOf('.', lastDotIndex - 1);
              const thirdLastDotIndex = albumDescription.lastIndexOf('.', secondLastDotIndex - 1);
              const forthLastDotIndex = albumDescription.lastIndexOf('.', thirdLastDotIndex - 1);
              const newParagraph = albumDescription.slice(0, forthLastDotIndex + 1);
              setAutoGeneratedAlbumDescripition(newParagraph);
              setAutoGeneratedDescription(true);
            })
            .catch((err1) => {
              console.error(err1);
            });
        })
        .catch((error) => {
          console.error(error);
        });
    }
  };

  useEffect(() => {
    handleGetAlbumInfo();
  }, [selectedAlbum]);

  const handleCustomAlbumDescripition = (description: string): void => {
    setCustomAlbumDescripition(description);
  };

  return (
    <>
      <Tab
        onClick={handleIconClick}
        heading={'Description'}
        open={openDescripition}
        active={activeStep >= 2}
      />
      <Collapse in={openDescripition} timeout={600} unmountOnExit>
        <Fade when={openDescripition} duration={500}>
          <div className="flex items-start justify-start gap-2 pb-2">
            <div>
              <Checkbox
                checked={autoGeneratedDescription}
                onChange={handleAutoGeneratedDescription}
                color="success"
              />
              <span className="ml-1 text-[12px]">Auto-Generated Description</span>
            </div>
            <div>
              <Checkbox
                checked={customDescription}
                onChange={handleCustomDescription}
                color="success"
              />
              <span className="ml-1 text-[12px]">Create Your Own</span>
            </div>
          </div>
          <textarea
            rows={4}
            disabled={!!autoGeneratedDescription}
            value={
              autoGeneratedDescription ? autoGeneratedAlbumDescripition : customAlbumDescripition
            }
            onChange={(e) => {
              handleCustomAlbumDescripition(e.target.value);
            }}
            className="w-full border border-[#919B9B] text-black rounded-lg text-[12px] outline-none p-3"
          />
        </Fade>
      </Collapse>
    </>
  );
};

export default step2;
