/* eslint-disable @typescript-eslint/explicit-function-return-type */
import React, { FC, useState, useEffect } from 'react';
import RightSide from '../../components/RightSide/index';
import Header from '../../components/Header/index';
import LeftSide from '../../components/LeftSide/index';
import Spinner from '../../components/Spinner/Spinner';
import { toast } from 'react-toastify';
import request from '../../api/request';
import CartModal from '../../Modals/CartModal';
import BlackWoodenFrame from '../../assets/PosterFrames/Black.svg';
import WhiteWoodenFrame from '../../assets/PosterFrames/White.svg';
import NuetralWoodenFrame from '../../assets/PosterFrames/Nuetral.svg';
import MetalFrame from '../../assets/PosterFrames/Metal.svg';

interface DataSetProps {
  time: number;
  levels: number[];
  songName: string;
  trackId: string;
}
interface SelectedAlbumProps {
  id: string;
  label: string;
  photo: string;
  singerName: string;
}

interface IPosterSize {
  value: string;
  unit: string;
}

interface IFrameProps {
  frameType: string;
  selectedFrame: string;
}

interface IStateColors {
  boxColor: string;
  posterColor: string;
  soundWaveColor: string;
  soundWaveNameColor: string;
  songTitleColor: string;
  descriptionColor: string;
}
interface IFrameProps {
  frameType: string;
  selectedFrame: string;
}
interface IPosterSize {
  value: string;
  unit: string;
}
interface IResponsePoster {
  frame: IFrameProps;
  size: IPosterSize;
  albumName: string;
  singerName: string;
  totalPrice: number;
  unitPrice: number;
  posterImage: string;
  posterQuantity: number;
  _id: string;
}
interface IResponseCart {
  success: boolean;
  cart: ICart;
}
interface ICart {
  _id: string;
  totalPoster: IResponsePoster[];
  totalPrice: number;
  shippingCost: number;
}

const index: FC = () => {
  // state for header
  const [cartItemsLength, setCartItemsLength] = useState<number>(0);
  const [open, setOpen] = useState(false);
  const [cart, setCart] = useState<ICart>({
    _id: '',
    totalPoster: [],
    totalPrice: 0,
    shippingCost: 0,
  });

  // state for leftside footer for poster alignment
  const [activeAlignment, setActiveAlignment] = useState<string>('text-left');

  // states for tabs active/inActive
  const [openDescripition, setOpenDescripition] = useState<boolean>(false);
  const [openTheme, setOpenTheme] = useState<boolean>(false);
  const [openStyles, setOpenStyles] = useState<boolean>(false);
  const [openSize, setOpenSize] = useState<boolean>(false);
  const [activeStep, setActiveStep] = useState<number>(1);
  // states for step # 1
  const [selected, setSelected] = useState<string>('');
  const [dataSets, setDataSets] = useState<DataSetProps[]>([]);
  const [selectedAlbum, setSelectedAlbum] = useState<SelectedAlbumProps>();
  // states for step # 2
  const [autoGeneratedAlbumDescripition, setAutoGeneratedAlbumDescripition] = useState<string>('');
  const [customAlbumDescripition, setCustomAlbumDescripition] = useState<string>('');
  const [autoGeneratedDescription, setAutoGeneratedDescription] = useState<boolean>(false);
  const [customDescription, setCustomDescription] = useState<boolean>(false);

  // states for step # 3
  // ------> states for colorSetting
  const [colors, setColors] = useState<IStateColors>({
    boxColor: '',
    posterColor: '',
    soundWaveColor: '',
    soundWaveNameColor: '',
    songTitleColor: '',
    descriptionColor: '',
  });

  const [selectedTemplate, setSelectedTemplate] = useState<string>('');
  // states for step # 4
  const [frame, setFrame] = useState<IFrameProps>({
    frameType: 'No Frame',
    selectedFrame: 'Poster Only',
  });
  const [selectedCanvas, setSelectedCanvas] = useState<string>('2-3 cm');
  // states for step # 5
  const [posterSize, setPosterSize] = useState<IPosterSize>({ value: '12 X 18', unit: 'inch' });
  // state for add to cart button
  const [addToCart, setAddToCart] = useState<boolean>(true);
  const [loading, setLoading] = useState<boolean>(false);

  const handleDataSets = (value: DataSetProps[]) => {
    setDataSets(value);
  };
  const posterDescription = autoGeneratedDescription
    ? autoGeneratedAlbumDescripition
    : customAlbumDescripition;

  const getSetColor = (currentColor: string, fieldName: string): void => {
    // const updatedColors = colors.map((item) => fieldName === item)
    setColors((prevState) => ({ ...prevState, [fieldName]: currentColor }));
  };

  const handleResetData = (): void => {
    // left side
    setDataSets([]);
    setActiveAlignment('text-left');

    setSelectedTemplate('');
    setSelected('');
    // right side
    setFrame({
      frameType: 'No Frame',
      selectedFrame: 'Poster Only',
    });
    setPosterSize({ value: '12 X 18', unit: 'inch' });
    setAutoGeneratedAlbumDescripition('');
    setCustomAlbumDescripition('');
    setAutoGeneratedDescription(false);
    setCustomDescription(false);
    setOpenDescripition(false);
    setOpenTheme(false);
    setOpenStyles(false);
    setOpenSize(false);
    setActiveStep(1);
  };

  const getCartData = (cartId: string): void => {
    setLoading?.(true);
    request<IResponseCart>('get', `/cart/${cartId}`)
      .then((res) => {
        // eslint-disable-next-line @typescript-eslint/naming-convention
        const cart = res.data.cart;
        const data = {
          shippingCost: cart.shippingCost,
          totalPoster: cart.totalPoster,
          totalPrice: cart.totalPrice,
          _id: cart._id,
        };
        setCart(data);
        setCartItemsLength(res.data.cart.totalPoster.length);
        setLoading?.(false);
      })
      .catch((err) => {
        setLoading?.(false);
        toast.error(err.response.data.message);
      });
  };

  const handleClose = (): void => {
    setOpen(false);
  };

  const BackgroundFrame =
    frame.selectedFrame === 'Wooden Black'
      ? BlackWoodenFrame
      : frame.selectedFrame === 'Wooden Nuteral'
      ? NuetralWoodenFrame
      : frame.selectedFrame === 'Wooden White'
      ? WhiteWoodenFrame
      : frame.selectedFrame === 'Aluminium Metal'
      ? MetalFrame
      : '';
  useEffect(() => {
    const cartId = localStorage.getItem('cartId');
    if (cartId) {
      getCartData(cartId);
    }
  }, []);

  return (
    <>
      <div className="relative">
        {loading && <Spinner />}
        <Header
          HeaderTitle="Create Your Own Design"
          cartItemsLength={cartItemsLength}
          setOpen={setOpen}
        />
        <div className="flex h-[85vh]">
          <LeftSide
            dataSets={dataSets}
            albumDescripition={posterDescription}
            selectedAlbum={selectedAlbum}
            colors={colors}
            setColors={setColors}
            activeAlignment={activeAlignment}
            setActiveAlignment={setActiveAlignment}
            selectedTemplate={selectedTemplate}
            frame={frame}
            BackgroundFrame={BackgroundFrame}
          />
          <RightSide
            // props for step # 1
            selected={selected}
            setSelected={setSelected}
            handleDataSets={handleDataSets}
            selectedAlbum={selectedAlbum}
            setSelectedAlbum={setSelectedAlbum}
            // props for step # 2
            autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
            setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
            customAlbumDescripition={customAlbumDescripition}
            setCustomAlbumDescripition={setCustomAlbumDescripition}
            autoGeneratedDescription={autoGeneratedDescription}
            setAutoGeneratedDescription={setAutoGeneratedDescription}
            customDescription={customDescription}
            setCustomDescription={setCustomDescription}
            // props for step # 3
            boxColor={colors.boxColor}
            posterColor={colors?.posterColor}
            soundWaveColor={colors.soundWaveColor}
            songTitleColor={colors.songTitleColor}
            descriptionColor={colors.descriptionColor}
            soundWaveNameColor={colors.soundWaveNameColor}
            getSetColor={getSetColor}
            selectedTemplate={selectedTemplate}
            setSelectedTemplate={setSelectedTemplate}
            // props for step # 4
            setLoading={setLoading}
            frame={frame}
            setFrame={setFrame}
            selectedCanvas={selectedCanvas}
            setSelectedCanvas={setSelectedCanvas}
            // props for step # 5
            posterSize={posterSize}
            setPosterSize={setPosterSize}
            // add to cart btn
            addToCart={addToCart}
            setAddToCart={setAddToCart}
            handleResetData={handleResetData}
            getCartData={getCartData}
            // tabs active/inActive states
            openDescripition={openDescripition}
            setOpenDescripition={setOpenDescripition}
            openTheme={openTheme}
            setOpenTheme={setOpenTheme}
            openStyles={openStyles}
            setOpenStyles={setOpenStyles}
            openSize={openSize}
            setOpenSize={setOpenSize}
            activeStep={activeStep}
            setActiveStep={setActiveStep}
          />
        </div>
      </div>
      <CartModal
        setLoading={setLoading}
        open={open}
        handleClose={handleClose}
        cart={cart}
        setCart={setCart}
        getCartData={getCartData}
      />
    </>
  );
};

export default index;
