const index: FC = () => {
  // state for leftside footer for poster alignment
  const [activeAlignment, setActiveAlignment] = useState<string>('text-left');

  // states for step # 1
  const [dataSets, setDataSets] = useState<DataSetProps[]>([]);
  const [selectedAlbum, setSelectedAlbum] = useState<SelectedAlbumProps>();
  // states for step # 2
  // ------> states for description
  const [autoGeneratedAlbumDescripition, setAutoGeneratedAlbumDescripition] = useState<string>('');
  const [customAlbumDescripition, setCustomAlbumDescripition] = useState<string>('');
  // ------> states for checkboxes
  const [autoGeneratedDescription, setAutoGeneratedDescription] = useState<boolean>(false);
  const [customDescription, setCustomDescription] = useState<boolean>(false);

  // states for step # 3
  // ------> states for colorSetting
  const [primaryColor, setPrimaryColor] = useState<string>('');
  const [boxColor, setBoxColor] = useState<string>('#D3D3D3');
  const [posterColor, setPosterColor] = useState<boolean>(true);
  const [soundWaveColor, setSoundWaveColor] = useState<boolean>(true);
  const [songTitleColor, setSongTitleColor] = useState<boolean>(true);
  const [selectedTemplate, setSelectedTemplate] = useState<string>('');

  // states for step # 4
  // ------> states for setting frame size
  const [posterSize, setPosterSize] = useState<string>('1218');
  // state for add to cart button
  const [addToCart, setAddToCart] = useState<boolean>(true);
  // state to manage data of items in cart

  // const [cartItem, setCartItem] = useState<ItemsProps>({});

  const handleDataSets = (value: DataSetProps[]) => {
    setDataSets(value);
  };
  const posterDescription = autoGeneratedDescription
    ? autoGeneratedAlbumDescripition
    : customAlbumDescripition;

  useGetPrimaryColor(selectedAlbum?.photo, setPrimaryColor);
  return (
    <>
      <Header HeaderTitle="Create Your Own Design" />
      <div className="flex h-[85vh]">
        <LeftSide
          dataSets={dataSets}
          albumDescripition={posterDescription}
          selectedAlbum={selectedAlbum}
          boxColor={boxColor}
          posterColor={posterColor ? 'bg-white' : 'bg-black'}
          soundWaveColor={soundWaveColor ? 'black' : 'black'}
          songTitleColor={songTitleColor ? 'text-black' : 'text-black'}
          activeAlignment={activeAlignment}
          setActiveAlignment={setActiveAlignment}
          selectedTemplate={selectedTemplate}
        />
        <RightSide
          // props for step # 1
          handleDataSets={handleDataSets}
          selectedAlbum={selectedAlbum}
          setSelectedAlbum={setSelectedAlbum}
          // props for step # 2
          autoGeneratedAlbumDescripition={autoGeneratedAlbumDescripition}
          setAutoGeneratedAlbumDescripition={setAutoGeneratedAlbumDescripition}
          customAlbumDescripition={customAlbumDescripition}
          setCustomAlbumDescripition={setCustomAlbumDescripition}
          autoGeneratedDescription={autoGeneratedDescription}
          setAutoGeneratedDescription={setAutoGeneratedDescription}
          customDescription={customDescription}
          setCustomDescription={setCustomDescription}
          // props for step # 3
          primaryColor={primaryColor}
          setBoxColor={setBoxColor}
          posterColor={posterColor}
          setPosterColor={setPosterColor}
          soundWaveColor={soundWaveColor}
          setSoundWaveColor={setSoundWaveColor}
          songTitleColor={songTitleColor}
          setSongTitleColor={setSongTitleColor}
          selectedTemplate={selectedTemplate}
          setSelectedTemplate={setSelectedTemplate}
          // props for step # 4
          posterSize={posterSize}
          setPosterSize={setPosterSize}
          addToCart={addToCart}
          setAddToCart={setAddToCart}
        />
      </div>
    </>
  );
};

export default index;
