interface DataSetProps {
  time: number;
  levels: number[];
  songName: string;
  trackId: string;
}
interface SelectedAlbumProps {
  id: string;
  label: string;
  photo: string;
  singerName: string;
}

interface IPosterSize {
  value: string;
  unit: string;
}

interface IFrameProps {
  frameType: string;
  selectedFrame: string;
}

interface IStateColors {
  boxColor: string;
  posterColor: string;
  soundWaveColor: string;
  songTitleColor: string;
  descriptionColor: string;
}

